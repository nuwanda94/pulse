#!/usr/bin/env python3
"""Run a controlled Pulse load test and write BENCHMARKS.md.

CI-friendly defaults:
  * ``--dry-run`` writes a template with no invented RPS/latency numbers.
  * ``--live`` runs Locust headless against ``--host`` for a short window and
    records measured RPS plus latency percentiles.

Never hand-edit performance figures in README.md; regenerate this file instead.

Examples::

    python scripts/benchmark.py --dry-run
    python scripts/benchmark.py --live --host http://127.0.0.1:8000 --users 5 --time 10s
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Sequence

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "BENCHMARKS.md"
LOCUSTFILE = ROOT / "locustfile.py"


@dataclass(frozen=True)
class EndpointStats:
    name: str
    requests: int
    failures: int
    rps: float
    p50_ms: float
    p95_ms: float
    p99_ms: float


@dataclass(frozen=True)
class BenchmarkReport:
    generated_at: str
    mode: str
    host: str
    users: int
    spawn_rate: float
    duration: str
    endpoints: list[EndpointStats]
    notes: list[str]


def _percentile(sorted_values: Sequence[float], pct: float) -> float:
    if not sorted_values:
        return 0.0
    if len(sorted_values) == 1:
        return float(sorted_values[0])
    k = (len(sorted_values) - 1) * (pct / 100.0)
    lo = int(k)
    hi = min(lo + 1, len(sorted_values) - 1)
    frac = k - lo
    return float(sorted_values[lo] * (1.0 - frac) + sorted_values[hi] * frac)


def stats_from_latencies(
    name: str,
    latencies_ms: Sequence[float],
    duration_s: float,
    failures: int = 0,
) -> EndpointStats:
    ordered = sorted(float(v) for v in latencies_ms)
    n = len(ordered)
    rps = (n / duration_s) if duration_s > 0 and n else 0.0
    return EndpointStats(
        name=name,
        requests=n,
        failures=failures,
        rps=round(rps, 3),
        p50_ms=round(_percentile(ordered, 50), 3),
        p95_ms=round(_percentile(ordered, 95), 3),
        p99_ms=round(_percentile(ordered, 99), 3),
    )


def render_markdown(report: BenchmarkReport) -> str:
    lines = [
        "# Pulse benchmarks",
        "",
        "Generated by `scripts/benchmark.py`. Do not invent numbers by hand.",
        "",
        f"- Generated at (UTC): `{report.generated_at}`",
        f"- Mode: `{report.mode}`",
        f"- Host: `{report.host}`",
        f"- Users: `{report.users}`",
        f"- Spawn rate: `{report.spawn_rate}`",
        f"- Duration: `{report.duration}`",
        "",
    ]
    if report.mode == "dry-run":
        lines.extend(
            [
                "No live load test was executed. Re-run with `--live` against a",
                "running Pulse stack to populate RPS and latency percentiles.",
                "",
            ]
        )
    if report.endpoints:
        lines.extend(
            [
                "| Endpoint | Requests | Failures | RPS | p50 (ms) | p95 (ms) | p99 (ms) |",
                "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
            ]
        )
        for item in report.endpoints:
            lines.append(
                f"| `{item.name}` | {item.requests} | {item.failures} | "
                f"{item.rps} | {item.p50_ms} | {item.p95_ms} | {item.p99_ms} |"
            )
        lines.append("")
    if report.notes:
        lines.append("## Notes")
        lines.append("")
        for note in report.notes:
            lines.append(f"- {note}")
        lines.append("")
    return "\n".join(lines) + "\n"


def _parse_locust_stats_csv(path: Path, duration_s: float) -> list[EndpointStats]:
    import csv

    endpoints: list[EndpointStats] = []
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            name = (row.get("Name") or row.get("name") or "").strip()
            if not name or name.lower() == "aggregated":
                continue
            requests = int(float(row.get("Request Count") or row.get("Requests") or 0))
            failures = int(float(row.get("Failure Count") or row.get("Failures") or 0))
            rps_raw = row.get("Requests/s") or row.get("RPS") or ""
            rps = float(rps_raw) if rps_raw not in ("", None) else (
                requests / duration_s if duration_s > 0 else 0.0
            )
            p50 = float(row.get("50%") or row.get("Median Response Time") or 0)
            p95 = float(row.get("95%") or 0)
            p99 = float(row.get("99%") or 0)
            endpoints.append(
                EndpointStats(
                    name=name,
                    requests=requests,
                    failures=failures,
                    rps=round(rps, 3),
                    p50_ms=round(p50, 3),
                    p95_ms=round(p95, 3),
                    p99_ms=round(p99, 3),
                )
            )
    return endpoints


def _duration_to_seconds(value: str) -> float:
    raw = value.strip().lower()
    if raw.endswith("s"):
        return float(raw[:-1])
    if raw.endswith("m"):
        return float(raw[:-1]) * 60.0
    if raw.endswith("h"):
        return float(raw[:-1]) * 3600.0
    return float(raw)


def run_locust_live(
    host: str,
    users: int,
    spawn_rate: float,
    duration: str,
    api_key: str,
) -> list[EndpointStats]:
    if not LOCUSTFILE.exists():
        raise FileNotFoundError(f"missing locustfile: {LOCUSTFILE}")
    duration_s = _duration_to_seconds(duration)
    with tempfile.TemporaryDirectory(prefix="pulse-bench-") as tmp:
        prefix = Path(tmp) / "locust"
        env = os.environ.copy()
        env["PULSE_API_KEY"] = api_key
        cmd = [
            sys.executable,
            "-m",
            "locust",
            "-f",
            str(LOCUSTFILE),
            "--host",
            host,
            "--headless",
            "-u",
            str(users),
            "-r",
            str(spawn_rate),
            "-t",
            duration,
            "--csv",
            str(prefix),
            "--only-summary",
        ]
        completed = subprocess.run(cmd, env=env, check=False, capture_output=True, text=True)
        stats_path = Path(f"{prefix}_stats.csv")
        if not stats_path.exists():
            raise RuntimeError(
                "locust did not write stats CSV.\n"
                f"exit={completed.returncode}\n"
                f"stdout={completed.stdout[-2000:]}\n"
                f"stderr={completed.stderr[-2000:]}"
            )
        return _parse_locust_stats_csv(stats_path, duration_s)


def build_report(args: argparse.Namespace) -> BenchmarkReport:
    generated_at = datetime.now(UTC).replace(microsecond=0).isoformat()
    notes = [
        "Numbers are measured by this script; they are not copied from marketing claims.",
        "Results depend on hardware, network, and whether rate limits are relaxed.",
    ]
    if args.dry_run or not args.live:
        return BenchmarkReport(
            generated_at=generated_at,
            mode="dry-run",
            host=args.host,
            users=args.users,
            spawn_rate=args.spawn_rate,
            duration=args.time,
            endpoints=[],
            notes=notes
            + ["Dry-run only; start the stack and pass --live to measure throughput."],
        )
    endpoints = run_locust_live(
        host=args.host,
        users=args.users,
        spawn_rate=args.spawn_rate,
        duration=args.time,
        api_key=args.api_key,
    )
    return BenchmarkReport(
        generated_at=generated_at,
        mode="live",
        host=args.host,
        users=args.users,
        spawn_rate=args.spawn_rate,
        duration=args.time,
        endpoints=endpoints,
        notes=notes,
    )


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Pulse load-test benchmark runner")
    parser.add_argument("--host", default=os.environ.get("PULSE_BENCH_HOST", "http://127.0.0.1:8000"))
    parser.add_argument("--users", type=int, default=int(os.environ.get("PULSE_BENCH_USERS", "5")))
    parser.add_argument(
        "--spawn-rate",
        type=float,
        default=float(os.environ.get("PULSE_BENCH_SPAWN_RATE", "2")),
    )
    parser.add_argument("--time", default=os.environ.get("PULSE_BENCH_TIME", "10s"))
    parser.add_argument("--api-key", default=os.environ.get("PULSE_API_KEY", "bench-key"))
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--live",
        action="store_true",
        help="Run Locust against --host and record measured stats",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Write BENCHMARKS.md template without running a load test (CI default)",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Also print the report as JSON on stdout",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    report = build_report(args)
    markdown = render_markdown(report)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown, encoding="utf-8")
    if args.json:
        payload = asdict(report)
        print(json.dumps(payload, indent=2))
    else:
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
